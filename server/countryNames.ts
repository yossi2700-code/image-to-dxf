/**
 * Convert a 2-letter country code to a flag emoji
 */
export function countryCodeToFlag(code: string): string {
  return String.fromCodePoint(
    ...Array.from(code.toUpperCase()).map(c => 0x1F1E6 + c.charCodeAt(0) - 65)
  );
}

/**
 * Get Hebrew country name with flag emoji from a 2-letter code
 * e.g. "IL" → "🇮🇱 ישראל"
 */
export function getHebrewCountryDisplay(code: string): string {
  const flag = countryCodeToFlag(code);
  const name = COUNTRY_NAMES_HE[code.toUpperCase()] ?? code;
  return `${flag} ${name}`;
}
